// Builds manifest.txt (craft-fonts manifest format read by the web editors' served-fonts loader):
// Cyrillic+Latin Google Fonts, each tied to a TTF pinned to a google/fonts commit. The editors
// fetch `gfonts/<commit>/<licence>/<family>/<file>` from raw.githubusercontent.com when a family is
// picked or hovered (see brand-editors.ps1).
// Usage: node build-catalog.mjs   (needs network; GitHub API is used unauthenticated)
import { writeFileSync } from 'node:fs';
const J = async u => { const r = await fetch(u, { headers: { 'user-agent': 'vravio-font-lab' } }); if (!r.ok) throw new Error(u + ' -> ' + r.status); return r.json(); };

const commit = (await J('https://api.github.com/repos/google/fonts/commits/main')).sha;
const root = await J(`https://api.github.com/repos/google/fonts/git/trees/${commit}`);

// Larger files are left out: a font fetched when its menu row is hovered must arrive quickly (these
// are CJK families that also cover Cyrillic).
const MAX_BYTES = 5 << 20;
const dirs = new Map();                       // "adventpro" -> { lic: "ofl", files: ["AdventPro[wdth,wght].ttf", ...] }
for (const lic of ['ofl', 'apache', 'ufl']) {   // the licence folders of google/fonts
  const sha = root.tree.find(x => x.path === lic).sha;
  const tree = await J(`https://api.github.com/repos/google/fonts/git/trees/${sha}?recursive=1`);
  if (tree.truncated) throw new Error(lic + ' tree truncated');
  for (const e of tree.tree) {
    const m = /^([^/]+)\/([^/]+\.ttf)$/.exec(e.path);   // top level of the family folder only (no static/)
    if (!m || e.size > MAX_BYTES || (dirs.has(m[1]) && dirs.get(m[1]).lic !== lic)) continue;
    (dirs.get(m[1]) ?? dirs.set(m[1], { lic, files: [] }).get(m[1])).files.push(m[2]);
  }
}

const fsrc = (await J('https://api.fontsource.org/v1/fonts?subsets=cyrillic'))
  .filter(f => f.type === 'google' && f.subsets.includes('cyrillic') && f.subsets.includes('latin') && f.styles.includes('normal') && f.weights.includes(400));

// Families whose files name themselves otherwise (picking them in a menu would find no font):
// checked by registering every file with the editors' font engine.
const EXCLUDE = new Set(['m-plus-rounded-1c']);   // registers as "Rounded Mplus 1c"
const out = [], missing = [];
for (const f of fsrc) {
  if (EXCLUDE.has(f.id)) { missing.push(f.id); continue; }
  const entry = dirs.get(f.id.replace(/-/g, ''));
  if (!entry) { missing.push(f.id); continue; }
  const files = entry.files;
  const up = files.filter(n => !/italic/i.test(n));
  const reg = up.find(n => /-Regular\.ttf$/.test(n));
  const vf = up.find(n => /\[.*\]\.ttf$/.test(n));
  const bold = up.find(n => /-Bold\.ttf$/.test(n));
  const file = reg ?? vf;
  if (!file) { missing.push(f.id); continue; }
  const dir = `${entry.lic}/${f.id.replace(/-/g, '')}`;
  out.push({ id: f.id, f: f.family, c: f.category, w: f.weights, ttf: `${dir}/${file}`, ...(reg && bold ? { bold: `${dir}/${bold}` } : {}), ...(vf && !reg ? { vf: 1 } : {}) });
}
const enc = p => p.split('/').map(encodeURIComponent).join('/');
// Fontsource categories as the editors' font class keys.
const CLASS = { 'serif': 'serif', 'sans-serif': 'sansSerif', 'monospace': 'monospace', 'handwriting': 'handwritten', 'display': 'decorative' };
const lines = ['# Generated by build-catalog.mjs from google/fonts@' + commit + ' (OFL/Apache fonts; see third-party-notices).', '# family | style | file | scripts | licence | licence file | sha256 | source | class'];
for (const f of out) {
  // Fields 4-8 (scripts, licence, licence file, sha256, source) are left empty; the 9th is the
  // font menu class, which the editors' class filters use before the files are fetched.
  const cls = /slab/i.test(f.f) && f.c === 'serif' ? 'slabSerif' : CLASS[f.c];
  const tail = cls ? ` |  |  |  |  |  | ${cls}` : '';
  lines.push(`${f.f} | Regular | gfonts/${commit}/${enc(f.ttf)}${tail}`);
  if (f.bold) lines.push(`${f.f} | Bold | gfonts/${commit}/${enc(f.bold)}${tail}`);
}
writeFileSync('manifest.txt', lines.join('\n') + '\n');
console.log({ commit: commit.slice(0, 10), total: fsrc.length, ok: out.length, missing: missing.length, vf: out.filter(x => x.vf).length, withBold: out.filter(x => x.bold).length });
if (missing.length) console.log('missing:', missing.join(', '));
